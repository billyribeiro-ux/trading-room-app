#!/usr/bin/env node
/**
 * Generates `src/lib/content/emoji-picker.ts` from the emoji picker markup inside
 * `evidence-dumps/TIER1-fetched/views/page.welcome.html`.
 *
 * ## Why this exists
 *
 * The reference's badge editor has an emoji button, and behind it 678 lines of inline picker markup:
 * a search box and six groups holding 635 emoji, each a `<span title="name">` around the character.
 * Ours rendered the BUTTON and nothing behind it — a control whose only effect is its own presence,
 * which this project forbids.
 *
 * ## Why generated rather than transcribed
 *
 * 635 emoji is not something to retype, and the markup is line-broken in two different ways
 * (`</span\n><span` and one per line) which is exactly the sort of thing a human transcription gets
 * subtly wrong. The template stays the single source of truth; this is the only transform.
 *
 * ## It FAILS LOUD
 *
 * The group titles are asserted against the six the capture contains, and the total against 635. If
 * a re-fetch changes either, this stops rather than silently emitting a shorter picker — a picker
 * missing a category looks complete to anyone who does not know what is absent.
 *
 * Run: node apps/controller/scripts/extract-emoji-picker.mjs [--out <path>]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const SOURCE = resolve(ROOT, 'evidence-dumps/TIER1-fetched/views/page.welcome.html');
const outIndex = process.argv.indexOf('--out');
const OUT = outIndex === -1 ? resolve(ROOT, 'src/lib/content/emoji-picker.ts') : resolve(process.argv[outIndex + 1]);

/** The six the capture holds, in the order it holds them. */
const EXPECTED_GROUPS = ['Frequently used', 'People', 'Nature', 'Objects', 'Places', 'Symbols'];
const EXPECTED_TOTAL = 635;

const html = readFileSync(SOURCE, 'utf8');
const start = html.indexOf('intercom-composer-emoji-popover');
if (start === -1) throw new Error('emoji picker markup not found in page.welcome.html');
const end = html.indexOf('</form>', start);
const region = end === -1 ? html.slice(start) : html.slice(start, end);

const groups = [];
for (const part of region.split('<div class="intercom-emoji-picker-group">').slice(1)) {
  const title = /intercom-emoji-picker-group-title">([^<]+)<\/div>/.exec(part);
  if (!title) continue;
  /*
    `[\s\S]` and a non-greedy body: the spans are written BOTH one-per-line and run together as
    `</span\n><span`, so a line-anchored pattern finds a fraction of them. The first attempt at this
    matched 9 of 635 for exactly that reason.
  */
  const emoji = [...part.matchAll(/title="([^"]+)"\s*>\s*([^<\s][^<]*?)\s*<\/span/g)].map((m) => ({
    name: m[1],
    char: m[2]
  }));
  groups.push({ title: title.group ?? title[1], emoji });
}

const titles = groups.map((g) => g.title);
if (JSON.stringify(titles) !== JSON.stringify(EXPECTED_GROUPS)) {
  throw new Error(`emoji groups changed: expected ${EXPECTED_GROUPS.join(', ')}; got ${titles.join(', ')}`);
}
const total = groups.reduce((n, g) => n + g.emoji.length, 0);
if (total !== EXPECTED_TOTAL) {
  throw new Error(`emoji count changed: expected ${EXPECTED_TOTAL}, got ${total}`);
}

const file = `/*
 * GENERATED by scripts/extract-emoji-picker.mjs — DO NOT EDIT.
 *
 * Source: the inline picker markup in
 * evidence-dumps/TIER1-fetched/views/page.welcome.html, which the reference's badge editor opens
 * from its \`#emoji-picker\` button. Six groups, ${EXPECTED_TOTAL} emoji, each a
 * \`<span title="name">char</span>\`.
 *
 * Regenerate with: pnpm --filter controller emoji:extract
 */
export interface EmojiGroup {
  readonly title: string;
  readonly emoji: readonly { readonly name: string; readonly char: string }[];
}

export const EMOJI_GROUPS: readonly EmojiGroup[] = ${JSON.stringify(groups, null, 2)};

/** ${EXPECTED_TOTAL} across ${EXPECTED_GROUPS.length} groups, asserted at generation time. */
export const EMOJI_TOTAL = ${total};
`;

writeFileSync(OUT, file);
console.log(`emoji-picker: ${groups.length} groups, ${total} emoji -> ${OUT}`);
